"""Export the View API response models as JSON Schema: ``uv run python -m plexus.api.export_schema``."""

from __future__ import annotations

import json
import sys
from pathlib import Path

from pydantic.json_schema import models_json_schema

from plexus.api.models import EXPORTED

DEFAULT_PATH = Path(__file__).resolve().parents[4] / "docs" / "view-api.schema.json"


def build_schema() -> dict:
    _, defs = models_json_schema([(m, "serialization") for m in EXPORTED], title="Plexus View API")
    defs["title"] = "Plexus View API response models"
    defs["description"] = (
        "Generated by plexus.api.export_schema. Endpoints: GET /api/tenants -> TenantsResponse; "
        "/api/{tenant}/inventory -> InventoryResponse; /api/{tenant}/graph -> GraphResponse; "
        "/api/{tenant}/flow -> FlowResponse; /api/{tenant}/stream (SSE, event 'toolcall', data = ToolCallEvent); "
        "/api/{tenant}/step/{n} -> StepResponse; /api/{tenant}/why/{id} -> WhyResponse; /api/{tenant}/recall/{id} -> RecallResponse; "
        "/api/queries/{name} -> QueryText; /api/results -> Crucible results JSON (opaque). Errors: ErrorBody."
    )
    return defs


def main() -> None:
    path = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_PATH
    path.write_text(json.dumps(build_schema(), indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
