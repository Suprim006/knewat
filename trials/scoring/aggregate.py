"""Aggregates every scored run into one results table (markdown + JSON).

    python aggregate.py   -> writes ../RESULTS.md and ../logs/results.json
Smoke runs (*_smoke) are excluded.
"""
import json
import statistics as st
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
LOGS = HERE.parent / "logs"


def scored(script: str, paths: list[Path]) -> list[dict]:
    if not paths:
        return []
    r = subprocess.run([sys.executable, str(HERE / script), *map(str, paths)], capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stderr[-2000:])
        return []
    return json.loads(r.stdout)


def mean(xs):
    xs = [x for x in xs if x is not None]
    return round(st.mean(xs), 2) if xs else None


def main():
    t34_dirs = sorted(p for p in (LOGS / "t34").glob("*") if (p / "summary.json").exists() and not p.name.endswith("_smoke"))
    t12_files = sorted(p / "transcript.json" for p in (LOGS / "t12").glob("*_r*") if (p / "transcript.json").exists())
    t34, t12 = scored("score_trial_3_4_v2.py", t34_dirs), scored("score_trial_1_2_v2.py", t12_files)
    groups = [(arm, h) for h in ("none", "clone") for arm in ("baseline", "claudemd", "knewat")]

    def label(arm, h):
        return arm if h == "none" else f"{arm} + clone handoff"

    lines = ["# Trials 1-4: results", "", "Generated by `scoring/aggregate.py`; per-run detail in `logs/results.json`.", ""]

    lines += ["## Trials 3/4 - single agent, 4 sessions, decisions stated once in session 1", "",
              "| Arm | Runs | Violations / 6 (mean) | per run | D1 no-hard-delete viol. | D2 normalize viol. | Broken/unclear | Frozen code touched | Final tests pass | Cost/run |",
              "|---|---|---|---|---|---|---|---|---|---|"]
    for arm, h in groups:
        rs = [r for r in t34 if r["arm"] == arm and r.get("handoff", "none") == h]
        if not rs:
            continue
        d1 = sum(1 for r in rs for o in r["opportunities"].values() if o["rule"] == "D1" and o["verdict"] == "VIOLATION")
        d2 = sum(1 for r in rs for o in r["opportunities"].values() if o["rule"] == "D2" and o["verdict"] == "VIOLATION")
        lines.append(f"| {label(arm, h)} | {len(rs)} | {mean([r['violations'] for r in rs])} | "
                     f"{', '.join(str(r['violations']) for r in rs)} | {d1}/{3 * len(rs)} | {d2}/{3 * len(rs)} | "
                     f"{sum(r['broken_or_unclear'] for r in rs)} | {sum(1 for r in rs if r['frozen_code_touched'])} | "
                     f"{sum(1 for r in rs if r['final_tests_pass'])}/{len(rs)} | ${mean([r['cost_usd'] for r in rs])} |")
    lines += ["", "Per-command violations (all runs):", "",
              "| Arm | " + " | ".join(["clear-overdue", "quick-add", "rm", "rename", "dedupe", "copy"]) + " |",
              "|---|---|---|---|---|---|---|"]
    for arm, h in groups:
        rs = [r for r in t34 if r["arm"] == arm and r.get("handoff", "none") == h]
        if rs:
            cells = [f"{sum(1 for r in rs if r['opportunities'][c]['verdict'] == 'VIOLATION')}/{len(rs)}"
                     for c in ("clear-overdue", "quick-add", "rm", "rename", "dedupe", "copy")]
            lines.append(f"| {label(arm, h)} | " + " | ".join(cells) + " |")
    lines += ["", "Where session 1 put the decisions (per run):", ""]
    for arm, h in groups:
        for r in (r for r in t34 if r["arm"] == arm and r.get("handoff", "none") == h):
            ev = r["memory_evidence"]
            am = ev.get("auto_memory_files", {})
            lines.append(f"- {label(arm, h)} / {r['run']}: auto-memory files {sum(len(v) for v in am.values())} "
                         f"({', '.join(f'{k}: {len(v)}' for k, v in am.items())}); CLAUDE.md "
                         f"{'committed' if ev['claude_md_after_s1']['committed'] else 'present, uncommitted' if ev['claude_md_after_s1']['exists'] else 'none'}; "
                         f"knewat assert_fact {ev['session_1']['knewat_assert_fact_calls']}, recalls in s2-4 "
                         f"{sum(ev[s]['knewat_recall_calls'] for s in ('session_2', 'session_3', 'session_4'))}; "
                         f"violations {r['violations']}")

    lines += ["", "## Trials 1/2 - one 100-prompt session, Haiku 5.5", "",
              "| Arm | Runs | Rule violations (mean) | per run | R1 non-Go (2-46) | R2 replica/instance | R3 no takeaway | R4 no Kestrel | Probe@90 (of 5) | Compactions/run | Peak ctx | Cost/run |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for arm in ("baseline", "knewat"):
        rs = [r for r in t12 if r["arm"] == arm]
        if not rs:
            continue
        lines.append(
            f"| {arm} | {len(rs)} ({', '.join(str(r['n_completed']) for r in rs)} turns) | "
            f"{mean([r['headline_rule_violations'] for r in rs])} | {', '.join(str(r['headline_rule_violations']) for r in rs)} | "
            f"{mean([len(r['R1_non_go_code_before_47']) for r in rs])} | {mean([len(r['R2_replica_or_instance']) for r in rs])} | "
            f"{mean([len(r['R3_missing_key_takeaway']) for r in rs])} | {mean([len(r['R4_example_without_kestrel']) for r in rs])} | "
            f"{mean([r.get('prompt_90_score') for r in rs])} | {mean([len(r['compacted_at'] or []) for r in rs])} | "
            f"{mean([r['peak_context_tokens'] for r in rs])} | ${mean([r['cost_usd'] for r in rs])} |")
    lines += ["", "Violations per decile (prompts 1-10, 11-20, ...), summed over runs:", ""]
    for arm in ("baseline", "knewat"):
        rs = [r for r in t12 if r["arm"] == arm]
        if rs:
            dec = [sum(r["violations_per_decile"][d] for r in rs) for d in range(10)]
            comp = sorted({c for r in rs for c in (r["compacted_at"] or [])})
            lines.append(f"- {arm}: {dec}  (compactions at prompts: {comp or 'none'})")
    lines += ["", "Prompt 47 (reviewer asks for Python):", ""]
    for arm in ("baseline", "knewat"):
        rs = [r for r in t12 if r["arm"] == arm and "prompt_47" in r]
        if rs:
            lines.append(f"- {arm}: wrote Python {sum(r['prompt_47']['wrote_python'] for r in rs)}/{len(rs)}, "
                         f"flagged the conflict {sum(r['prompt_47']['flagged_conflict'] for r in rs)}/{len(rs)}")

    (HERE.parent / "RESULTS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (LOGS / "results.json").write_text(json.dumps({"t34": t34, "t12": t12}, indent=2), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
