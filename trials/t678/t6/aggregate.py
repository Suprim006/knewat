"""Aggregates every scored Trial 6 run (smoke*/underscore dirs excluded) into a markdown section + results.json.

    python3 aggregate.py [--include-smoke]     -> prints markdown, writes ../../logs/t6/results.json
"""
import json
import statistics as st
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import score  # noqa: E402

LOGS = HERE.parent.parent / "logs" / "t6"
ARMS = ("baseline", "claudemd", "plexus")
CMDS = [c for _s, c, _e in score.COMMANDS]


def mean(xs):
    xs = [x for x in xs if x is not None]
    return round(st.mean(xs), 3) if xs else None


def am_summary(am):
    files = am["files"]
    return f"{len(files)}" + (f" ({'/'.join(sorted(files))}; archived-mention {sum(f['mentions_archived'] for f in files.values())}, " 
                              f"utc-mention {sum(f['mentions_utc_z'] for f in files.values())})" if files else "")


def main(argv=None):
    include_smoke = "--include-smoke" in (argv if argv is not None else sys.argv[1:])
    dirs = sorted(p for p in LOGS.glob("*_*")
                  if (p / "summary.json").exists() and not p.name.startswith("_")
                  and (include_smoke or "smoke" not in p.name.split("_", 1)[1]))
    runs = [score.score_run(p) for p in dirs]
    sums = {p.name: json.loads((p / "summary.json").read_text(encoding="utf-8")) for p in dirs}
    L = ["# Trial 6 - a decision that spans two repos: results", "",
         "Generated by `t678/t6/aggregate.py`. 6 opportunities per run: 3 new tasksync commands x {X1 archived never "
         "exported, X2 UTC-Z timestamps}. Only VIOLATION counts; MISSING / BROKEN / NOT_APPLICABLE / NOT_RUN are shown separately.", "",
         "| Arm | Runs | Violations / 6 (mean) | per run | X1 viol. | X2 viol. | Not scored (M/B/NA/NR) | Existing export-json fixed (X1 / X2) | Final tests A / B | Cost/run |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    for arm in ARMS:
        rs = [r for r in runs if r["arm"] == arm]
        if not rs:
            continue
        def ns(k):
            return sum(r["not_scored"].get(k, 0) for r in rs)
        fixed = [r["existing_export_json_after"].get("s4", {}) for r in rs]
        L.append(f"| {arm} | {len(rs)} | {mean([r['violations'] for r in rs])} | {', '.join(str(r['violations']) for r in rs)} | "
                 f"{sum(r['violations_by_rule']['X1'] for r in rs)}/{3 * len(rs)} | {sum(r['violations_by_rule']['X2'] for r in rs)}/{3 * len(rs)} | "
                 f"{ns('MISSING')}/{ns('BROKEN')}/{ns('NOT_APPLICABLE')}/{ns('NOT_RUN')} | "
                 f"{sum(f.get('X1') == 'COMPLIANT' for f in fixed)}/{len(rs)} / {sum(f.get('X2') == 'COMPLIANT' for f in fixed)}/{len(rs)} | "
                 f"{sum(bool(r['final_tests_pass']['A']) for r in rs)}/{len(rs)} / {sum(bool(r['final_tests_pass']['B']) for r in rs)}/{len(rs)} | "
                 f"${mean([r['cost_usd'] for r in rs])} |")
    L += ["", "Per-command violations (X1 / X2, all runs):", "", "| Arm | " + " | ".join(CMDS) + " |", "|---|" + "---|" * len(CMDS)]
    for arm in ARMS:
        rs = [r for r in runs if r["arm"] == arm]
        if rs:
            cells = [f"{sum(r['opportunities'][c + '/X1']['verdict'] == 'VIOLATION' for r in rs)}/{len(rs)} / "
                     f"{sum(r['opportunities'][c + '/X2']['verdict'] == 'VIOLATION' for r in rs)}/{len(rs)}" for c in CMDS]
            L.append(f"| {arm} | " + " | ".join(cells) + " |")
    L += ["", "Memory evidence per run (where did session 1 put the decisions; did sessions 2-4 consult them):", ""]
    for arm in ARMS:
        for r in (r for r in runs if r["arm"] == arm):
            ev = r["memory_evidence"]
            am = ev["auto_memory"]
            s24 = ("session_2", "session_3", "session_4")
            cm_w = [f"{w['where']}" for s in ("session_1",) + s24 for w in ev[s]["claude_md_writes"]]
            cm_r = [f"{s[-1]}:{w['where']}" for s in s24 for w in ev[s]["claude_md_reads"]]
            cm_files = ", ".join(k + ": " + ("committed" if v["committed"] else "uncommitted")
                                   for k, v in ev["claude_md_files_after_s1"].items()) or "none"
            L.append(f"- **{r['run']}**: violations {r['violations']}/6 {r['not_scored'] or ''}; "
                     f"s1 CLAUDE.md on disk: {ev['claude_md_location_after_s1']} "
                     f"({cm_files}); "
                     f"CLAUDE.md write locations (tool_use) {cm_w or 'none'}; reads in s2-4 {cm_r or 'none'}; "
                     f"auto-memory A cwd: {am_summary(am['tinytasks (A cwd)'])}, B cwd: {am_summary(am['tasksync (B cwd)'])}; "
                     f"s1 touched in B: {ev.get('s1_changed_files_B') or 'nothing'}; "
                     f"plexus s1 assert_fact {ev['session_1']['plexus_assert_fact']}/start_session {ev['session_1']['plexus_start_session']}, "
                     f"s2-4 recall {[ev[s]['plexus_recall'] for s in s24]}/start_session {[ev[s]['plexus_start_session'] for s in s24]}; "
                     f"denials {[ev[s]['permission_denials'] for s in ('session_1',) + s24]}, is_error {[ev[s]['is_error'] for s in ('session_1',) + s24]}; "
                     f"export-json after s1..s4 {[tuple(v.values()) for v in r['existing_export_json_after'].values()]}")
    L += ["", "Per-session cost (USD):", ""]
    for arm in ARMS:
        for p in dirs:
            if sums[p.name]["arm"] == arm:
                L.append(f"- {p.name}: " + ", ".join(f"{k[-1]}=${(v.get('cost_usd') or 0):.3f}" for k, v in sums[p.name]["sessions"].items())
                         + f" (total ${sums[p.name]['total_cost_usd']})")
    (LOGS / "results.json").write_text(json.dumps(runs, indent=2), encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
