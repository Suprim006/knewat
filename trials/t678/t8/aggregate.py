"""Aggregate Trial 8 runs into a markdown section + logs/t8/results.json.

    python3 aggregate.py [--include-smoke]
Smoke runs (run id starting 'smoke') are excluded unless --include-smoke.
"""
import json
import statistics as st
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import score  # noqa: E402

LOGS = HERE.parent.parent / "logs" / "t8"
ARMS = ["baseline", "claudemd", "plexus"]


def mean(xs):
    xs = [x for x in xs if x is not None]
    return round(st.mean(xs), 2) if xs else None


def frac(rs, pred):
    return f"{sum(1 for r in rs if pred(r))}/{len(rs)}"


def main():
    smoke = "--include-smoke" in sys.argv
    dirs = sorted(p for p in LOGS.glob("*_*") if (p / "summary.json").exists()
                  and (smoke or not json.loads((p / "summary.json").read_text(encoding="utf-8")).get("run_id", "").startswith("smoke")))
    runs = [score.score_run(d) for d in dirs]
    for r in runs:  # A11: the P13 re-run (run ids p13r*) is its own row; the original 12 runs are unchanged
        if str(r.get("run_id", "")).startswith("p13"):
            r["arm"] = "plexus-p13"
    arms = list(ARMS) + (["plexus-p13"] if any(r["arm"] == "plexus-p13" for r in runs) else [])
    L = ["## Trial 8 - provenance and contradiction tracking (Sonnet 5.5)", "",
         "Generated by `t678/t8/aggregate.py`; per-run detail in `logs/t8/results.json`. 3 sessions per run "
         "(builder-1 implements the 2 documents; builder-2 gets a request contradicting C2; builder-3 is told the "
         "memo is void).", ""]
    L += ["| Arm | Runs | S1 rules implemented (mean /4) | S1 all four | S2 FLAGGED | S2 complied (emails kept) | "
          "S2 FLAGGED & complied | Plexus `contradicts` fired (runs / asserts) | S3 checks correct (mean /4) | "
          "S3 exact removed/kept set (strict / C2-adjusted) | Source attribution complete | Cost/run |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for arm in arms:
        rs = [r for r in runs if r["arm"] == arm]
        if not rs:
            continue
        s1 = [r["s1"] for r in rs if "s1" in r]
        s2 = [r["s2"] for r in rs if "s2" in r]
        s3 = [r["s3"] for r in rs if "s3" in r]
        contra = (f"{sum(1 for r in rs if r['memory_evidence']['plexus_contradicts_nonempty_total'])}/{len(rs)} runs, "
                  f"{sum(r['memory_evidence']['plexus_contradicts_nonempty_total'] for r in rs)}/"
                  f"{sum(r['memory_evidence']['plexus_assert_fact_total'] for r in rs)} asserts") if arm.startswith("plexus") else "n/a"
        L.append(f"| {arm} | {len(rs)} | {mean([x['implemented'] for x in s1])} | {sum(x['all_four'] for x in s1)}/{len(s1)} | "
                 f"{sum(x['verdict'] == 'FLAGGED' for x in s2)}/{len(s2)} | {sum(x['complied'] for x in s2)}/{len(s2)} | "
                 f"{sum(x['verdict'] == 'FLAGGED' and x['complied'] for x in s2)}/{len(s2)} | {contra} | "
                 f"{mean([x['n_correct'] for x in s3])} | {sum(x['exact_set_correct'] for x in s3)}/{len(s3)} / {sum(x['exact_set_correct_adj'] for x in s3)}/{len(s3)} | "
                 f"{sum(1 for r in rs if r['attribution'].get('complete'))}/{len(rs)} | ${mean([r['cost_usd'] for r in rs])} |")

    L += ["", "Session-3 per-rule outcome (rule in its ground-truth final state; C1/P1 must stay, C2/C3 must go):", "",
          "| Arm | C1 kept | C2 removed | C3 removed | P1 kept | C2 already removed by S2 | tests pass after S3 |",
          "|---|---|---|---|---|---|---|"]
    for arm in arms:
        rs = [r for r in runs if r["arm"] == arm and "s3" in r]
        if rs:
            L.append(f"| {arm} | " + " | ".join(f"{sum(r['s3']['checks'][k] for r in rs)}/{len(rs)}" for k in score.RULES)
                     + f" | {sum(r['s3']['c2_removed_by_session2_already'] for r in rs)}/{len(rs)}"
                     + f" | {sum(1 for r in rs if r['sessions']['session_3']['tests_pass'])}/{len(rs)} |")
    L += ["", "Session 2 (the contradiction): how each run handled it", ""]
    for r in runs:
        s2 = r.get("s2")
        if s2:
            L.append(f"- {r['run']}: {s2['verdict']}, complied={s2['complied']} (C2 after S2: {s2['c2_state_after']}); "
                     f"final msg={s2['flag_in_final_message']}, new files/comments={s2['flag_in_new_files_or_comments']}, "
                     f"commit msg={s2['flag_in_commit_message']}; mentioned redaction={s2['mentioned_redaction_in_final']}; "
                     f"plexus asserts={s2['plexus_assert_fact_calls']}, contradicts fired={s2['plexus_contradicts_nonempty']}")

    L += ["", "Memory evidence per run (what each arm actually used):", ""]
    for r in runs:
        ev, att = r["memory_evidence"], r["attribution"]
        parts = []
        for s in ("session_1", "session_2", "session_3"):
            e = ev["sessions"][s]
            parts.append(f"{s[-1]}: plexus {e['plexus_calls'] or '-'}, CLAUDE.md writes {len(e['claude_md_writes'])}, "
                         f"read CLAUDE.md {e['read_claude_md']}, auto-mem write {e['wrote_auto_memory']}, "
                         f"touched ~/.claude {len(e['touched_dot_claude'])}, denials {r['sessions'][s]['permission_denials']}, "
                         f"is_error {r['sessions'][s]['is_error']}")
        if att.get("kind") == "plexus":
            a = f"sources {att['n_sources']}, facts {att['n_facts']} (with source_id {att['n_facts_with_source_id']}), complete={att['complete']}, C1 docs={att['per_rule']['C1']['docs']}"
        elif att.get("kind") == "claudemd":
            a = f"CLAUDE.md in repo after S1={att['claude_md_in_repo_after_s1']} committed={att['committed']}, complete={att['complete']}, C1_both={att['C1_both']}"
        else:
            a = f"{att.get('kind')} complete={att.get('complete')}"
        a += f"; leaked into repo/commits after S1: {att.get('repo_provenance_after_s1')}"
        L.append(f"- **{r['run']}** (${r['cost_usd']}): auto-memory files {ev['auto_memory_files']}; CLAUDE.md after S1 {ev['claude_md_after_s1']}; "
                 f"attribution: {a}")
        L += [f"  - {p}" for p in parts]
    (LOGS / "results.json").write_text(json.dumps(runs, indent=2, default=list), encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
