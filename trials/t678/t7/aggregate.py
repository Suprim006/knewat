"""Aggregates every scored Trial 7 run: prints a markdown section and writes ../../logs/t7/results.json.
Runs whose id starts with `smoke` are excluded (use --include-smoke to see them).

    python3 aggregate.py [--include-smoke]
"""
import json
import statistics as st
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import score  # noqa: E402

LOGS = HERE.parent.parent / "logs" / "t7"
ARMS = ("baseline", "claudemd", "plexus")


def mean(xs):
    xs = [x for x in xs if x is not None]
    return round(st.mean(xs), 3) if xs else None


def pct(n, d):
    return f"{n}/{d}"


def main():
    include_smoke = "--include-smoke" in sys.argv
    dirs = sorted(p for p in LOGS.glob("*_*") if (p / "summary.json").exists()
                  and (include_smoke or "smoke" not in p.name))
    results = [score.score_run(p) for p in dirs]
    (LOGS / "results.json").write_text(json.dumps(results, indent=2), encoding="utf-8")

    L = ["## Trial 7: memory shared between agents on parallel worktrees + ci-bot", "",
         "Per run 3 opportunities: Y1 x2 (B1: `quick-add`, `postpone`), Y2 x1 (B2: `status`). Generated by "
         "`t678/t7/aggregate.py`; per-run detail in `logs/t7/results.json`.", "",
         "| Arm | Runs | Violations/3 (mean) | per run | Y1 viol. | Y2 viol. | Broken/unclear | A followed Y1 | Tests pass (A/B1/B2) | Cost/run |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    for arm in ARMS:
        rs = [r for r in results if r["arm"] == arm]
        if not rs:
            continue
        tp = [sum(1 for r in rs if r["final_tests_pass"].get(k)) for k in ("A", "B1", "B2")]
        L.append(f"| {arm} | {len(rs)} | {mean([r['violations'] for r in rs])} | "
                 f"{', '.join(str(r['violations']) for r in rs)} | {pct(sum(r['violations_Y1'] for r in rs), 2 * len(rs))} | "
                 f"{pct(sum(r['violations_Y2'] for r in rs), len(rs))} | {sum(r['broken_unclear_missing'] for r in rs)} | "
                 f"{pct(sum(1 for r in rs if r['A_snooze_followed_Y1']['verdict'] == 'COMPLIANT'), len(rs))} | "
                 f"{tp[0]}/{tp[1]}/{tp[2]} | ${mean([r['cost_usd'] for r in rs])} |")

    L += ["", "Per-command verdicts (C=compliant, V=violation, U=unclear, B=broken):", "",
          "| Arm | run | quick-add (Y1) | postpone (Y1) | status (Y2) | A snooze (Y1 sanity) |", "|---|---|---|---|---|---|"]
    for r in results:
        o = r["opportunities"]
        g = lambda k: o[k]["verdict"][0] if o.get(k, {}).get("verdict") else "?"  # noqa: E731
        L.append(f"| {r['arm']} | {r['run']} | {g('quick-add')} | {g('postpone')} | {g('status')} | "
                 f"{r['A_snooze_followed_Y1']['verdict'][0]} |")

    L += ["", "### Memory evidence per run", "",
          "| Run | auto-memory dir shared wt_a/wt_b? | A wrote CLAUDE.md | committed on feat-a | reached main | B1 recall / B2 recall | "
          "recall surfaced Y1 / Y2 | Plexus agent ids ok | B read CI_NOTES (B1/B2) | B peeked at A (B1/B2) | denials (A/B1/B2) |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in results:
        e = r["memory_evidence"]
        s = e["sessions"]
        cm = e["claude_md"]
        rc = lambda k: s[k]["plexus_calls"].get("recall", 0)  # noqa: E731
        ids_ok = all(s[k]["plexus_agent_id_ok"] for k in s)
        L.append(
            f"| {r['run']} | {e['auto_memory']['shared_between_wt_a_and_wt_b']} | {bool(cm['A_wrote_claude_md'])} | "
            f"{cm['A_committed_claude_md_on_feat_a']} | {cm['claude_md_reached_main_checkout']} | {rc('B1')} / {rc('B2')} | "
            f"{s['B1']['plexus_recall_surfaced_Y1'] or s['B2']['plexus_recall_surfaced_Y1']} / "
            f"{s['B1']['plexus_recall_surfaced_Y2'] or s['B2']['plexus_recall_surfaced_Y2']} | {ids_ok} | "
            f"{e['B_touched_CI_NOTES']['B1']}/{e['B_touched_CI_NOTES']['B2']} | {e['B_peeked_at_A']['B1']}/{e['B_peeked_at_A']['B2']} | "
            f"{s['A']['permission_denials']}/{s['B1']['permission_denials']}/{s['B2']['permission_denials']} |")

    L += ["", "Plexus tool calls by session (name:count):", ""]
    for r in results:
        for k, sv in r["memory_evidence"]["sessions"].items():
            if sv["plexus_calls"] or r["arm"] == "plexus":
                L.append(f"- {r['run']} {k} ({sv.get('model')}): {sv['plexus_calls']} agent_ids={sv['plexus_agent_ids']}")

    L += ["", "Claude Code auto-memory (dir each session loaded; files in it right after A):", ""]
    for r in results:
        am = r["memory_evidence"]["auto_memory"]
        L.append(f"- {r['run']}: loaded {{{', '.join(f'{k}: ...{v[-70:]}' for k, v in am['dir_loaded_by_session'].items())}}}; "
                 f"shared A/B1={am['shared_between_wt_a_and_wt_b']}; files after A in B1's dir: {am['files_in_B1_dir_written_by_A_session']}")
    L.append("")
    out = "\n".join(L)
    print(out)
    return out


if __name__ == "__main__":
    main()
